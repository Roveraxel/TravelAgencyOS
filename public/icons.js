export function icon(name) {
  return ICONS[name] || '';
}

export function channelIcon(channel = '') {
  const c = String(channel).toLowerCase();
  if (c.includes('whatsapp')) return ICONS.chat;
  if (c.includes('insta')) return ICONS.camera;
  if (c.includes('email')) return ICONS.mail;
  if (c.includes('excel') || c.includes('csv')) return ICONS.sheet;
  return ICONS.globe;
}
